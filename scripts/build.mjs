import {readFile, writeFile} from 'node:fs/promises';
const source = (await readFile(new URL('../src/mobile.mjs', import.meta.url), 'utf8')).replace(/^export /gm, '');
const css = await readFile(new URL('../src/mobile.css', import.meta.url), 'utf8');
const mascot = (await readFile(new URL('../src/mascot.mjs', import.meta.url), 'utf8')).replace(/^export /gm, '');
const frames = await Promise.all(['peek','blink','wave','drag1','drag2','drag3','wave1','wave2','wave3','wave4','pick1','pick2','pick3','pick4','apple1','apple2','apple3','apple4','apple5','apple6','apple7','apple8',...Array.from({length:16},(_,i)=>'apple-smooth'+(i+1)),...Array.from({length:16},(_,i)=>'pick-smooth'+(i+1))].map(async name => 'data:image/png;base64,' + (await readFile(new URL('../assets/girl-' + name + '.png', import.meta.url))).toString('base64')));
const result = `// Generated by npm run build. No runtime dependencies or second React copy.
window.__ModuleLoader__.load({
  id: 'dsh-plugin-ui-for-mobile',
  factory(require) {
    const React = require('react');
${source}
${mascot}
    const mascotFrames = ${JSON.stringify(frames)};
    return {
      inject: ['slots', 'layout', 'locale'],
      apply(ctx) {
        ctx.effect(() => ctx.locale.register('mobileUi', {
          zh: {close: '关闭侧边栏', open: '打开会话侧边栏'},
          en: {close: 'Close sidebar', open: 'Open conversation sidebar'},
        }));
        ctx.effect(() => {
          const adapter = installMobile(ctx, ${JSON.stringify(css)});
          function Navigation({t}) {
            const state = React.useSyncExternalStore(adapter.subscribe, adapter.getSnapshot);
            const previous = React.useRef(state);
            const trigger = React.useRef(null);
            React.useEffect(() => {
              if (state !== 'closed') return;
              return installMascot(trigger.current, mascotFrames);
            }, [state]);
            React.useEffect(() => {
              if (previous.current === 'open' && state === 'closed'
                && (!document.activeElement || document.activeElement === document.body
                  || document.activeElement.closest('[data-dsh-mobile-sidebar]'))) {
                trigger.current?.focus({preventScroll: true});
              }
              previous.current = state;
            }, [state]);
            if (state === 'inactive') return null;
            if (state === 'open') return React.createElement('button', {
              type: 'button', className: 'dsh-mobile-backdrop',
              'aria-label': t('close'), onClick: adapter.close,
            });
            return React.createElement('button', {
              ref: trigger, type: 'button', className: 'dsh-mobile-whale',
              'aria-label': t('open'), 'aria-expanded': false,
              onClick: adapter.toggle,
            }, React.createElement('img', {src: mascotFrames[0], alt: '', draggable: false}));
          }
          let stop;
          try {
            stop = ctx.slots.inject('shell.overlay', () => ctx.slots.register({
              name: 'shell.overlay', id: 'mobile-ui.backdrop', locale: 'mobileUi',
            }, Navigation));
          } catch (error) { adapter.dispose(); throw error; }
          return () => { stop(); adapter.dispose(); };
        });
      },
    };
  },
});
`;
await writeFile(new URL('../client.js', import.meta.url), result);
console.log('Built client.js');
